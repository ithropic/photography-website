#!/usr/bin/env python3
"""Turn the photos in ``source/`` into web-ready images and a ``photos.js`` manifest.

Usage (from the project root):
    pip install pillow
    python tools/build_images.py

Workflow:
    1. Drop your full-size photos into ``source/`` (JPEG or PNG). Files are shown
       on the site in alphabetical order, so prefix them: 01-name.jpg, 02-name.jpg ...
    2. (Optional) Add descriptions in ``captions.json``: {"01-name.jpg": "Alt text"}.
    3. Run this script. It writes ``images/*.webp`` and ``photos.js``.
    4. Commit/deploy ``images/`` and ``photos.js``. ``source/`` never needs to be uploaded.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT / "source"
IMAGES_DIR = ROOT / "images"
CAPTIONS_FILE = ROOT / "captions.json"
MANIFEST_FILE = ROOT / "photos.js"

SUPPORTED_SUFFIXES = {".jpg", ".jpeg", ".png"}
WIDTHS = (800, 1600)  # target widths in px; capped at the original's width
WEBP_QUALITY = 82


def load_captions(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise ValueError(f"{path.name} must be a JSON object of filename -> description")
    return {str(k): str(v) for k, v in data.items()}


def list_sources(directory: Path) -> list[Path]:
    return sorted(
        p for p in directory.iterdir()
        if p.is_file() and p.suffix.lower() in SUPPORTED_SUFFIXES
    )


def slugify(stem: str) -> str:
    """Reduce a filename stem to lowercase ASCII letters, digits and hyphens.

    Spaces, parentheses, commas and apostrophes in image URLs break ``srcset``
    parsing (the browser silently falls back to the smallest image), and
    filenames end up in public URLs, so output names are always made safe.
    """
    ascii_stem = unicodedata.normalize("NFKD", stem).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", ascii_stem.lower()).strip("-") or "photo"


def unique_slug(stem: str, used: set[str]) -> str:
    """Slugify ``stem`` and add a numeric suffix if another photo already took it."""
    base = slugify(stem)
    candidate, counter = base, 2
    while candidate in used:
        candidate = f"{base}-{counter}"
        counter += 1
    used.add(candidate)
    return candidate


def export_sizes(
    source: Path, out_dir: Path, out_stem: str
) -> tuple[list[tuple[int, str]], tuple[int, int]]:
    """Write resized WebP files for ``source``, named ``<out_stem>-<width>.webp``.

    Returns ([(width, filename), ...] smallest first, (original_width, original_height)).
    """
    with Image.open(source) as opened:
        image = ImageOps.exif_transpose(opened)  # respect camera rotation
        icc_profile = opened.info.get("icc_profile")
        image = image.convert("RGB")

    full_width, full_height = image.size
    # Cap each target at the original width (never upscale), then drop duplicates.
    widths = sorted({min(w, full_width) for w in WIDTHS})
    outputs: list[tuple[int, str]] = []

    for width in widths:
        height = round(full_height * width / full_width)
        resized = image if width == full_width else image.resize((width, height), Image.LANCZOS)
        filename = f"{out_stem}-{width}.webp"
        save_kwargs = {"quality": WEBP_QUALITY, "method": 6}
        if icc_profile:
            save_kwargs["icc_profile"] = icc_profile
        resized.save(out_dir / filename, "WEBP", **save_kwargs)
        outputs.append((width, filename))

    return outputs, (full_width, full_height)


def remove_stale(out_dir: Path, keep: set[str]) -> list[str]:
    removed = []
    for path in out_dir.glob("*.webp"):
        if path.name not in keep:
            path.unlink()
            removed.append(path.name)
    return removed


def write_manifest(photos: list[dict], path: Path) -> None:
    body = json.dumps(photos, indent=2, ensure_ascii=False)
    path.write_text(
        "// Generated by tools/build_images.py - do not edit by hand.\n"
        f"window.PHOTOS = {body};\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.parse_args()

    if not SOURCE_DIR.is_dir():
        print(f"error: {SOURCE_DIR} does not exist", file=sys.stderr)
        return 1

    sources = list_sources(SOURCE_DIR)
    if not sources:
        print(f"error: no .jpg/.png files found in {SOURCE_DIR}", file=sys.stderr)
        return 1

    IMAGES_DIR.mkdir(exist_ok=True)
    captions = load_captions(CAPTIONS_FILE)
    photos: list[dict] = []
    written: set[str] = set()
    used_stems: set[str] = set()

    for index, source in enumerate(sources, start=1):
        out_stem = unique_slug(source.stem, used_stems)
        outputs, (width, height) = export_sizes(source, IMAGES_DIR, out_stem)
        written.update(name for _, name in outputs)
        photos.append({
            "srcset": [{"width": w, "url": f"images/{name}"} for w, name in outputs],
            "width": width,
            "height": height,
            "alt": captions.get(source.name, f"Photograph {index}"),
        })
        print(f"  {source.name}: {', '.join(str(w) for w, _ in outputs)} px")

    for name in remove_stale(IMAGES_DIR, written):
        print(f"  removed stale {name}")

    write_manifest(photos, MANIFEST_FILE)
    print(f"Wrote {len(photos)} photos to {MANIFEST_FILE.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
